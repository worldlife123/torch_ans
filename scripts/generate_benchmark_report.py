#!/usr/bin/env python3
"""Render `benchmark_status.md` from `scripts/bench_version_matrix.py` outputs.

The numbers are produced locally on one machine (see the environment table in
the output) and committed; they are deliberately **not** generated by CI any
more, because the CI runners are virtualised CPUs whose throughput varies too
much between runs to compare releases.

Usage:
    python scripts/bench_version_matrix.py --version-label 0.2.1 --json 021.json
    python scripts/bench_version_matrix.py --version-label 0.3.0 --json 030.json
    python scripts/generate_benchmark_report.py --baseline 021.json \
        --candidate 030.json --output benchmark_status.md

The baseline/candidate arguments accept several JSON files (the codec/params
sections and the high-level section are usually measured with different batch
shapes and are therefore stored separately).
"""

from __future__ import annotations

import argparse
import json
from datetime import date
from pathlib import Path

FAMILIES = ("rans64", "rans32", "rans32_16")
INTERLEAVES = (1, 4, 32)
LOOKUPS = ("binary", "invcdf_dense", "invcdf_sparse", "alias")

LOOKUP_LABEL = {
    "binary": "binary search",
    "invcdf_dense": "inverse CDF (dense)",
    "invcdf_sparse": "inverse CDF (sparse)",
    "alias": "alias sampling",
}


def load(paths):
    records, meta = [], {}
    for p in paths:
        data = json.loads(Path(p).read_text())
        meta.update({k: v for k, v in data.items() if k != "records"})
        records.extend(data["records"])
    return meta, records


def index(records, section):
    out = {}
    for r in records:
        if r.get("section") != section:
            continue
        if section == "codec":
            key = (r["device"], r["family"], r["interleaves"], r["lookup"])
        elif section == "params":
            key = (r["device"], r["step"])
        else:
            key = (r["device"], r["variant"])
        out[key] = r
    return out


def fmt(value, digits=1):
    return "—" if value is None else f"{value:.{digits}f}"


def speedup(new, old):
    if new is None or old is None or not old:
        return "—"
    return f"{new / old:.2f}×"


def status_note(rec):
    if rec is None:
        return False, ""
    status = rec.get("status", "")
    if status == "ok":
        return False, ""
    if status == "unsupported":
        return True, "n/a"
    return True, "broken" if "differ" in status else "err"


def codec_table(old_codec, new_codec, device):
    lines = [
        "| family | interleave | symbol lookup | v0.2.1 encode | v0.3.0 encode | "
        "enc gain | v0.2.1 decode | v0.3.0 decode | dec gain |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for family in FAMILIES:
        for ilv in INTERLEAVES:
            for lookup in LOOKUPS:
                old = old_codec.get((device, family, ilv, lookup))
                new = new_codec.get((device, family, ilv, lookup))
                if old is None and new is None:
                    continue
                o_skip, o_note = status_note(old)
                n_skip, n_note = status_note(new)
                if o_skip and n_skip:
                    continue
                o_e = None if old is None or o_skip else old.get("encode")
                o_d = None if old is None or o_skip else old.get("decode")
                n_e = None if new is None or n_skip else new.get("encode")
                n_d = None if new is None or n_skip else new.get("decode")
                oe = f"{fmt(o_e)} ({o_note})" if o_skip else fmt(o_e)
                od = f"{fmt(o_d)} ({o_note})" if o_skip else fmt(o_d)
                ne = f"{fmt(n_e)} ({n_note})" if n_skip else fmt(n_e)
                nd = f"{fmt(n_d)} ({n_note})" if n_skip else fmt(n_d)
                lines.append(
                    f"| `{family}` | {ilv} | {LOOKUP_LABEL[lookup]} | {oe} | {ne} | "
                    f"{speedup(n_e, o_e)} | {od} | {nd} | {speedup(n_d, o_d)} |")
    return "\n".join(lines)


def params_table(old_params, new_params, device):
    lines = [
        "| step | table | v0.2.1 | v0.3.0 | gain |",
        "|---|---|---|---|---|",
    ]
    for step in ("pmf_to_cdf", "invcdf_dense", "invcdf_sparse"):
        old = old_params.get((device, step))
        new = new_params.get((device, step))
        if old is None and new is None:
            continue
        o_skip, o_note = status_note(old)
        n_skip, n_note = status_note(new)
        o = None if old is None or o_skip else old.get("ms")
        n = None if new is None or n_skip else new.get("ms")
        q = (new or old or {}).get("table_precision")
        q = "" if q is None else f"q={q}"
        lines.append(
            f"| `{step}` | {q} | "
            f"{'n/a' if o_skip else fmt(o, 3)} | "
            f"{'n/a' if n_skip else fmt(n, 3)} | "
            f"{speedup(o, n)} |")
    return "\n".join(lines)


def high_level_table(old_hl, new_hl, device):
    lines = [
        "| configuration | v0.2.1 encode | v0.3.0 encode | enc gain | "
        "v0.2.1 decode | v0.3.0 decode | dec gain |",
        "|---|---|---|---|---|---|---|",
    ]
    variants = [k[1] for k in new_hl if k[0] == device]
    variants += [k[1] for k in old_hl
                 if k[0] == device and k[1] not in variants]
    for variant in variants:
        old = old_hl.get((device, variant))
        new = new_hl.get((device, variant))
        o_skip, o_note = status_note(old)
        n_skip, n_note = status_note(new)
        o_e = None if old is None or o_skip else old.get("encode")
        o_d = None if old is None or o_skip else old.get("decode")
        n_e = None if new is None or n_skip else new.get("encode")
        n_d = None if new is None or n_skip else new.get("decode")
        lines.append(
            f"| {variant} | {fmt(o_e)} | {fmt(n_e)} | {speedup(n_e, o_e)} | "
            f"{fmt(o_d)} | {fmt(n_d)} | {speedup(n_d, o_d)} |")
    return "\n".join(lines)


def value(index_, device, family, ilv, lookup, phase):
    rec = index_.get((device, family, ilv, lookup))
    if rec is None or rec.get("status") != "ok":
        return None
    return rec.get(phase)


def rng(values):
    values = [v for v in values if v]
    if not values:
        return None
    return f"{min(values):.2f}×–{max(values):.2f}×"


def highlights(old_codec, new_codec, old_params, new_params, old_hl, new_hl,
               old_label, new_label):
    """A few release-level statements derived from the measurements."""
    lines = []

    def gains(device, ilv, lookup, phase):
        out = []
        for family in FAMILIES:
            o = value(old_codec, device, family, ilv, lookup, phase)
            n = value(new_codec, device, family, ilv, lookup, phase)
            if o and n:
                out.append(n / o)
        return out

    cpu1 = rng(gains("cpu", 1, "binary", "decode"))
    cpu1e = rng(gains("cpu", 1, "binary", "encode"))
    if cpu1:
        lines.append(f"- **CPU, unchanged configuration** (1-way, binary search): "
                     f"decode {cpu1}, encode {cpu1e}.")

    cpu4d = rng(gains("cpu", 4, "binary", "decode"))
    cpu4e = rng(gains("cpu", 4, "binary", "encode"))
    if cpu4d:
        old_ratio, new_ratio = [], []
        for family in FAMILIES:
            o1 = value(old_codec, "cpu", family, 1, "binary", "decode")
            o4 = value(old_codec, "cpu", family, 4, "binary", "decode")
            n1 = value(new_codec, "cpu", family, 1, "binary", "decode")
            n4 = value(new_codec, "cpu", family, 4, "binary", "decode")
            if o1 and o4:
                old_ratio.append(o4 / o1)
            if n1 and n4:
                new_ratio.append(n4 / n1)
        extra = ""
        if old_ratio and new_ratio:
            extra = (f" Interleaving only pays off in v{new_label}: 4-way/1-way "
                     f"decode is {min(old_ratio):.2f}×–{max(old_ratio):.2f}× in "
                     f"v{old_label} (a slowdown) and "
                     f"{min(new_ratio):.2f}×–{max(new_ratio):.2f}× in v{new_label}.")
        lines.append(f"- **CPU, 4-way interleaved**: decode {cpu4d}, "
                     f"encode {cpu4e}.{extra}")

    cuda1d = rng(gains("cuda", 1, "binary", "decode"))
    cuda1e = rng(gains("cuda", 1, "binary", "encode"))
    if cuda1d:
        lines.append(f"- **CUDA, 1-way**: essentially unchanged — decode {cuda1d}, "
                     f"encode {cuda1e}.")

    dense = rng(gains("cuda", 1, "invcdf_dense", "decode"))
    if dense:
        lines.append(f"- **CUDA, 1-way dense inverse CDF** is the one regression: "
                     f"{dense} (v{new_label} stages the table differently); the "
                     f"sparse table (`inverse_cdf_precision=\"auto\"`) is the "
                     f"replacement and lands back at ~1.0× of the v{old_label} "
                     f"dense number while using 1/256 of the memory.")

    i32 = value(new_codec, "cuda", "rans32_16", 32, "binary", "decode")
    i32e = value(new_codec, "cuda", "rans32_16", 32, "binary", "encode")
    if i32:
        lines.append(f"- **CUDA, 32-way warp kernels (new)**: {i32e:.0f} Msym/s "
                     f"encode, {i32:.0f} Msym/s decode — an order of magnitude "
                     f"above the 1-way path.")

    for device, label in (("cpu", "CPU"), ("cuda", "CUDA")):
        for step in ("pmf_to_cdf", "invcdf_dense"):
            o = old_params.get((device, step))
            n = new_params.get((device, step))
            if o and n and o.get("ms") and n.get("ms"):
                lines.append(f"- **{label} `{step}`**: {o['ms']:.3f} ms → "
                             f"{n['ms']:.3f} ms ({o['ms'] / n['ms']:.1f}×).")

    for device, label in (("cpu", "CPU"), ("cuda", "CUDA")):
        best_old = max((r for k, r in old_hl.items() if k[0] == device
                        and r.get("status") == "ok"),
                       key=lambda r: r["decode"], default=None)
        best_new = max((r for k, r in new_hl.items() if k[0] == device
                        and r.get("status") == "ok"),
                       key=lambda r: r["decode"], default=None)
        if best_old and best_new:
            lines.append(f"- **High-level API, best configuration on {label}**: "
                         f"decode {best_old['decode']:.1f} → "
                         f"{best_new['decode']:.1f} Msym/s "
                         f"({best_new['decode'] / best_old['decode']:.2f}×), "
                         f"encode {best_old['encode']:.1f} → "
                         f"{best_new['encode']:.1f} Msym/s.")
    return lines


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--baseline", nargs="+", required=True,
                   help="JSON files produced against the previous release")
    p.add_argument("--candidate", nargs="+", required=True,
                   help="JSON files produced against the current tree")
    p.add_argument("--output", default="benchmark_status.md")
    p.add_argument("--baseline-label", default=None)
    p.add_argument("--candidate-label", default=None)
    args = p.parse_args()

    old_meta, old_records = load(args.baseline)
    new_meta, new_records = load(args.candidate)
    old_label = args.baseline_label or old_meta.get("version", "baseline")
    new_label = args.candidate_label or new_meta.get("version", "candidate")
    old_codec, new_codec = index(old_records, "codec"), index(new_records, "codec")
    old_params, new_params = index(old_records, "params"), index(new_records, "params")
    old_hl, new_hl = index(old_records, "high_level"), index(new_records, "high_level")

    devices = [d for d in ("cpu", "cuda") if any(k[0] == d for k in new_codec)]

    out = []
    out.append("# Benchmark Status")
    out.append("")
    out.append(f"Local measurements of the rANS operators on one machine, "
               f"comparing **v{old_label}** and **v{new_label}** "
               f"(measured {date.today().isoformat()}).")
    out.append("")
    out.append("> These numbers are produced **locally and committed by hand**; "
               "the CI job that used to regenerate this file on every full-matrix "
               "run has been removed. CI runners are virtualised CPUs whose "
               "throughput varies by tens of percent between runs, which made the "
               "table useless for comparing releases (it could only ever show "
               "virtualisation noise, not a regression).")
    out.append("")
    out.append("## Environment")
    out.append("")
    out.append("| item | value |")
    out.append("|---|---|")
    out.append(f"| CPU | {new_meta.get('cpu')} |")
    out.append(f"| GPU | {new_meta.get('gpu')} |")
    out.append(f"| torch | {new_meta.get('torch')} |")
    out.append(f"| Python | {new_meta.get('python')} |")
    out.append(f"| torch intra-op threads | {new_meta.get('threads')} |")
    out.append(f"| workload | 8 distributions, alphabet 255 + bypass tail, "
               f"`freq_precision=15`, uniform-ish random PMF, in-range symbols |")
    out.append(f"| batch | 48 streams x 8192 symbols (CPU), "
               f"2048 streams x 8192 symbols (CUDA) |")
    out.append(f"| method | best of 3 passes x 10 stream clones, stream clones and "
               f"table builds outside the timed region, every configuration "
               f"verified to round-trip before it is timed |")
    out.append("")
    out.append("All throughput numbers are **Msymbol/s** (larger is better); "
               "`gain` is `v%s / v%s`. `n/a` = the operator does not exist in that "
               "release, `broken` = it exists but decoded to the wrong symbols "
               "(the benchmark refuses to time those)."
               % (new_label, old_label))
    out.append("")
    out.append("## Highlights")
    out.append("")
    out.extend(highlights(old_codec, new_codec, old_params, new_params,
                          old_hl, new_hl, old_label, new_label))
    out.append("")

    for device in devices:
        title = "CPU" if device == "cpu" else "CUDA"
        out.append(f"## Raw operators — {title}")
        out.append("")
        out.append(codec_table(old_codec, new_codec, device))
        out.append("")

    out.append("## Parameter build (`init_params` hot path)")
    out.append("")
    out.append("Latency in **ms** (smaller is better); `gain` is "
               "`v%s / v%s`." % (old_label, new_label))
    out.append("")
    for device in devices:
        out.append(f"### {'CPU' if device == 'cpu' else 'CUDA'}")
        out.append("")
        out.append(params_table(old_params, new_params, device))
        out.append("")

    out.append("## High-level API, end to end")
    out.append("")
    out.append("`TorchANSInterface.encode_with_indexes` / `decode_with_indexes` "
               "including the stream <-> bytes conversion, i.e. what an unchanged "
               "user program measures. 48 x 8192 symbols (CPU) / 256 x 8192 (CUDA).")
    out.append("")
    for device in devices:
        out.append(f"### {'CPU' if device == 'cpu' else 'CUDA'}")
        out.append("")
        out.append(high_level_table(old_hl, new_hl, device))
        out.append("")
    out.append("> Note: in v%s `impl=\"rans32_16\"` was silently shadowed by the "
               "`\"rans32\"` prefix match, so the v%s `rans32_16 default` row "
               "actually ran the `rans32` operators. The end-to-end numbers are "
               "also dominated by the stream <-> bytes conversion on both "
               "releases, so they move much less than the raw operators."
               % (old_label, old_label))
    out.append("")

    out.append("## Reproducing")
    out.append("")
    out.append("The raw JSON behind the tables above is committed under "
               "`benchmarks/`.")
    out.append("")
    out.append("```bash")
    out.append("# current tree")
    out.append("pip install . --no-build-isolation            # WITH_CUDA=1 for CUDA")
    out.append("python scripts/bench_version_matrix.py --version-label "
               f"{new_label} --best-effort \\")
    out.append(f"    --json benchmarks/v{new_label}-codec-params.json")
    out.append("python scripts/bench_version_matrix.py --version-label "
               f"{new_label} --best-effort \\")
    out.append("    --rows-cuda 256 --sections high_level \\")
    out.append(f"    --json benchmarks/v{new_label}-high_level.json")
    out.append("")
    out.append(f"# v{old_label} baseline (checked out and built in a worktree)")
    out.append(f"git worktree add --detach .bench/v{old_label} v{old_label}")
    out.append(f"cd .bench/v{old_label} && WITH_CUDA=1 python setup.py "
               "build_ext --inplace && cd -")
    out.append(f"cp scripts/bench_version_matrix.py .bench/v{old_label}/scripts/")
    out.append(f"PYTHONPATH=$PWD/.bench/v{old_label} \\")
    out.append(f"    python .bench/v{old_label}/scripts/bench_version_matrix.py \\")
    out.append(f"        --version-label {old_label} "
               f"--json benchmarks/v{old_label}-codec-params.json")
    out.append("")
    out.append("python scripts/generate_benchmark_report.py \\")
    out.append(f"    --baseline benchmarks/v{old_label}-codec-params.json "
               f"benchmarks/v{old_label}-high_level.json \\")
    out.append(f"    --candidate benchmarks/v{new_label}-codec-params.json "
               f"benchmarks/v{new_label}-high_level.json \\")
    out.append("    --output benchmark_status.md")
    out.append("```")
    out.append("")
    out.append("A version that cannot be built any more can be skipped; the report "
               "then shows `—` in that column and no gain.")
    out.append("")

    Path(args.output).write_text("\n".join(out) + "\n")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
