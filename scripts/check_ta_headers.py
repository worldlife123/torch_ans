"""Compile-check the `ta::` compatibility layer in both build modes.

`torch_ans/ta/` is the one place where the ATen build and the libtorch-stable-ABI
build have to agree on an interface: a missing overload or a `__host__`-only view
method breaks one of the two build modes, and the error surfaces at whichever call
site reaches it first rather than here.

This script therefore generates a throwaway translation unit that *uses* every
primitive the layer exposes (all the templates, both dispatch macros, the POD
views, the CUDA stream/guard/error macro) and compiles it four ways:

    aten-cpp    g++   -fsyntax-only   (torch/extension.h, no defines)
    stable-cpp  g++   -fsyntax-only   -DTORCH_ANS_STABLE_ABI
    aten-cu     nvcc  -c              -DWITH_CUDA
    stable-cu   nvcc  -c              -DTORCH_ANS_STABLE_ABI -DUSE_CUDA=1

The two `g++` combinations must pass; that is the actual stage-0 acceptance
criterion. The CUDA combinations are skipped (not failed) when no usable nvcc is
found, and are the reason this script looks for a specific toolkit: the machine
default may be a CUDA whose nvcc cannot compile the installed torch's headers
(see the note under `--cuda-home`).

Nothing is written into the repository: the TU lives in a temporary directory
and is deleted on exit unless `--keep` is given.

Usage::

    python scripts/check_ta_headers.py
    python scripts/check_ta_headers.py --no-cuda -v
    python scripts/check_ta_headers.py --cuda-home /usr/local/cuda-11.8 --ccbin /usr/bin/gcc-10
    python scripts/check_ta_headers.py --only-cuda     # only the nvcc half
"""

import argparse
import json
import os
import shutil
import subprocess
import sys
import sysconfig
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TA_DIR = ROOT / "torch_ans" / "ta"

#: Same value as poc/stable_abi/setup.py and, later, torch_ans/setup.py: the
#: lowest ABI a stable-ABI .so claims to support (torch 2.10).
TORCH_TARGET_VERSION = "0x020a000000000000"

#: The same floor as a version, for the skip decision below: the stable half of
#: the check needs torch's stable-ABI headers, which only exist from here on.
#: Kept in step with `torch_ans/_stable_C.STABLE_ABI_MIN_TORCH` and with
#: `TORCH_TARGET_VERSION` above (both are torch 2.10).
STABLE_ABI_MIN_TORCH = (2, 10)

#: One arch is enough to syntax-check kernels; sm_75 is what the POC used.
CUDA_ARCH = "compute_75,code=sm_75"

STABLE_DEFINES = [
    "-DTORCH_ANS_STABLE_ABI=1",
    "-DTORCH_TARGET_VERSION=" + TORCH_TARGET_VERSION,
]

#: The ATen build gates its CUDA section on WITH_CUDA (what setup.py defines),
#: the stable build on USE_CUDA (what makes the stable C shim declare the CUDA
#: entries).
ATEN_CU_DEFINES = ["-DWITH_CUDA=1"]
STABLE_CU_DEFINES = ["-DUSE_CUDA=1"]

CPP_TU = """// Generated by scripts/check_ta_headers.py - do not edit, do not commit.
#include "torch_api.hpp"

#include <cstdint>
#include <vector>

namespace {

// Every ta:: primitive a kernel or an op wrapper is expected to call, in one
// function, so that a syntax-only compile instantiates all of the templates
// (nothing here runs; the CUDA entry points below are the device side).
void ta_check_all(const std::vector<int64_t>& sizes) {
  ta::Tensor stream = ta::zeros(sizes, ta::ScalarType::Int);
  ta::zero_(stream);
  ta::Tensor filled = ta::zeros(sizes, ta::ScalarType::Int, ta::device_of(stream));
  ta::Tensor blank = ta::empty(sizes, ta::ScalarType::Int);
  (void)ta::empty_like(stream);
  (void)ta::new_empty(stream, sizes);
  (void)ta::new_zeros(stream, sizes);
  (void)ta::new_zeros_1d(stream, int64_t(4));
  (void)ta::zeros_like(stream);

  ta::Tensor c = ta::as_contiguous(blank);
  c = ta::contiguous(c);
  c = ta::clone(c);
  c = ta::reshape(c, sizes);
  c = ta::unsqueeze(c, int64_t(0));
  c = ta::select(c, int64_t(0), int64_t(0));
  c = ta::amax(c, int64_t(0), false);
  c = ta::to(c, ta::Device(ta::DeviceType::CPU, 0));
  c = ta::narrow(c, 1, 0, 1);
  c = ta::copy_(c, stream);

  ta::View1<int32_t> v1 = ta::view1<int32_t>(filled);
  ta::View2<int32_t> v2 = ta::view2<int32_t>(filled);
  v1.at(0) = v2.at(0, 0);
  (void)v1.ptr();
  (void)v1.numel;
  (void)v1.stride;
  (void)v2.row(0);
  (void)v2.size0;
  (void)v2.size1;
  (void)v2.stride0;
  (void)v2.stride1;

  int32_t* mutable_ptr = ta::data_ptr<int32_t>(filled);
  const int32_t* const_ptr = ta::const_data_ptr<int32_t>(filled);
  *mutable_ptr = *const_ptr;

  (void)ta::is_cuda(filled);
  (void)ta::is_cpu(filled);
  (void)ta::device_index(filled);

  int64_t total = 0;
  TA_DISPATCH_INTEGRAL(filled.scalar_type(), "ta_check_integral", [&] {
    total += (int64_t)ta::max_scalar<scalar_t>(filled);
  });
  TA_DISPATCH_FLOATING(filled.scalar_type(), "ta_check_floating", [&] {
    total += (int64_t)sizeof(scalar_t);
  });
  (void)total;

  ta::parallel_for(0, int64_t(1), 0, [](int64_t start, int64_t end) {
    (void)start;
    (void)end;
  });
  ta::resize2d(filled, 1, 1);
}

}  // namespace
"""

CU_TU = """// Generated by scripts/check_ta_headers.py - do not edit, do not commit.
#include "torch_api.hpp"

#include <cstdint>
#include <vector>

// The POD views are passed *by value* into a kernel, so they have to be
// trivially copyable and their methods have to be __host__ __device__.
__global__ void ta_check_kernel(ta::View2<int32_t> stream_view,
                                ta::View1<int32_t> symbol_view) {
  const int64_t b = threadIdx.x;
  if (b < stream_view.size0) {
    stream_view.at(b, 0) = symbol_view.at(b);
  }
}

namespace {

void ta_check_cuda(const std::vector<int64_t>& sizes) {
  ta::Tensor t = ta::zeros(sizes, ta::ScalarType::Int);
  ta::DeviceGuard guard(ta::device_index(t));
  cudaStream_t stream = ta::current_stream(t);
  ta_check_kernel<<<1, 1, 0, stream>>>(ta::view2<int32_t>(t),
                                       ta::view1<int32_t>(t));
  TA_CUDA_CHECK(cudaGetLastError());
  (void)ta::is_cuda(t);
}

}  // namespace
"""


def _torch_includes(needs_python: bool):
    """Include paths for the TU, asked of the *installed* torch.

    `ce.include_paths()` already lists `torch/include`, which is where torch's
    wheels keep their bundled pybind11 (`torch/include/pybind11`) - the standalone
    `pybind11` package is only added when it happens to be installed. It stopped
    being a dependency of torch_ans when the stable-ABI build landed (that build
    needs no pybind11 at all), so the ATen check must not require it either.
    """
    code = (
        "import json, sys, sysconfig\n"
        "from torch.utils import cpp_extension as ce\n"
        "paths = list(ce.include_paths())\n"
        "if %r:\n"
        "    paths.append(sysconfig.get_paths()['include'])\n"
        "    try:\n"
        "        import pybind11\n"
        "        paths.append(pybind11.get_include())\n"
        "    except ImportError:\n"
        "        pass\n"
        "print(json.dumps(paths))\n" % needs_python
    )
    out = subprocess.check_output([sys.executable, "-c", code], text=True)
    return ["-I" + p for p in json.loads(out)]


def _torch_probe():
    """(`torch.__version__`, `torch.version.cuda`) of the installed torch.

    Everything the skip decisions need, asked once so that the two answers come
    from the same process: the CUDA half needs a torch built with CUDA
    (`torch.version.cuda is not None`), the stable half a torch that has the
    stable ABI - a CPU-only wheel has no `c10/cuda` headers that can compile and
    a torch below `STABLE_ABI_MIN_TORCH` no `<torch/csrc/stable/...>` at all.
    """
    code = ("import json, torch\n"
            "print(json.dumps({'version': torch.__version__,\n"
            "                  'cuda': torch.version.cuda}))\n")
    return json.loads(subprocess.check_output([sys.executable, "-c", code], text=True))


def _version_tuple(version):
    """`(major, minor)` of a torch version string ('2.11.0+cu130' -> (2, 11))."""
    parts = []
    for chunk in version.split("+")[0].split(".")[:2]:
        digits = "".join(char for char in chunk if char.isdigit())
        parts.append(int(digits) if digits else 0)
    while len(parts) < 2:
        parts.append(0)
    return tuple(parts)


def _cxx_skip_reason():
    """Why the two `-fsyntax-only` combinations cannot be checked, or None.

    Windows has no compiler this check can use: MSVC is not a drop-in for
    `-fsyntax-only` and the mingw `g++` on the CI runners cannot parse ATen's
    headers (measured: `aten-cpp` fails there). The Windows build is covered by
    the extension build itself, which compiles every kernel with MSVC.
    """
    if sys.platform == "win32":
        return ("the g++ syntax check does not apply on Windows (the MSVC build "
                "of the extension is the real check)")
    if shutil.which("g++") is None:
        return "no g++ on PATH"
    return None


def _stable_skip_reason(probe):
    """Why the stable-ABI combinations cannot be checked, or None.

    `torch_api_stable.hpp` includes `<torch/csrc/stable/accelerator.h>`, which
    only ships from torch 2.10 on (the ABI this layer's stable backend and the
    prebuilt wheel target); with an older torch the honest answer is "not
    applicable", not "broken".
    """
    if _version_tuple(probe["version"]) >= STABLE_ABI_MIN_TORCH:
        return None
    return ("the installed torch (%s) predates the stable ABI "
            "(torch >= %s)" % (probe["version"],
                               ".".join(str(part) for part in STABLE_ABI_MIN_TORCH)))


def _cuda_torch_skip_reason(probe):
    """Why no CUDA combination can be checked, before even looking for nvcc."""
    if probe["cuda"] is None:
        return ("the installed torch is a CPU-only build (torch.version.cuda is "
                "None, so its c10/cuda headers cannot compile)")
    return None


def _find_nvcc(cuda_home):
    """nvcc from an explicit CUDA home, else the newest local /usr/local one.

    `shutil.which("nvcc")` comes last on purpose: on the development machine the
    one on PATH is CUDA 11.5, whose nvcc cannot compile this torch's headers,
    while /usr/local/cuda-11.8 can.
    """
    candidates = []
    if cuda_home:
        candidates.append(cuda_home)
    for env in ("TA_CUDA_HOME", "CUDA_HOME"):
        if os.environ.get(env):
            candidates.append(os.environ[env])
    candidates += ["/usr/local/cuda-11.8", "/usr/local/cuda"]
    for home in candidates:
        nvcc = Path(home) / "bin" / "nvcc"
        if nvcc.is_file():
            return nvcc, str(Path(home))
    found = shutil.which("nvcc")
    if found:
        return Path(found), str(Path(found).resolve().parent.parent)
    return None, None


def _find_ccbin(ccbin):
    if ccbin:
        return ccbin
    if os.environ.get("TA_CCBIN"):
        return os.environ["TA_CCBIN"]
    # nvcc 11.8 predates gcc 11 and refuses it ("unsupported GNU version");
    # gcc-10 is what the successful local builds used.
    for candidate in ("/usr/bin/gcc-10", "/usr/bin/g++-10"):
        if Path(candidate).is_file():
            return candidate
    return None


def _cuda_skip_reason(cuda_home, probe):
    reason = _cuda_torch_skip_reason(probe)
    if reason:
        return reason
    nvcc, _ = _find_nvcc(cuda_home)
    if nvcc is None:
        return "no nvcc found (pass --cuda-home or set CUDA_HOME)"
    return None


def _run(command, verbose):
    if verbose:
        print("    " + " ".join(str(part) for part in command))
    return subprocess.run([str(part) for part in command],
                          capture_output=True, text=True)


def _check(name, command, verbose):
    result = _run(command, verbose)
    if result.returncode == 0:
        print(f"[ok]   {name}")
        return True
    print(f"[FAIL] {name}")
    output = (result.stdout + result.stderr).strip()
    # Keep the failure output short but complete enough to act on: the first
    # errors are the real ones, everything after that is usually fallout.
    lines = output.splitlines()
    for line in lines[:40]:
        print("       " + line)
    if len(lines) > 40:
        print(f"       ... ({len(lines) - 40} more lines)")
    return False


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--cuda-home", default=None,
                        help="CUDA toolkit root to take nvcc from "
                             "(default: $TA_CUDA_HOME, $CUDA_HOME, "
                             "/usr/local/cuda-11.8, /usr/local/cuda)")
    parser.add_argument("--ccbin", default=None,
                        help="host compiler for nvcc (default: $TA_CCBIN, "
                             "/usr/bin/gcc-10 when present)")
    parser.add_argument("--no-cuda", action="store_true",
                        help="only run the two g++ combinations")
    parser.add_argument("--only-cuda", action="store_true",
                        help="only run the two nvcc combinations (what the "
                             "pytest guard uses; the g++ ones have their own test)")
    parser.add_argument("--keep", action="store_true",
                        help="keep the generated translation units")
    parser.add_argument("-v", "--verbose", action="store_true",
                        help="print every compiler command line")
    args = parser.parse_args(argv)
    if args.no_cuda and args.only_cuda:
        parser.error("--no-cuda and --only-cuda are mutually exclusive")

    torch_probe = _torch_probe()
    #: A combination that does not apply here is skipped, not failed: a CPU-only
    #: torch cannot compile the c10/cuda headers, a torch below 2.10 has no
    #: stable-ABI ones, and Windows has no g++ that can parse ATen's headers.
    cxx_reason = _cxx_skip_reason()
    stable_reason = _stable_skip_reason(torch_probe)

    aten_includes = _torch_includes(needs_python=True)
    stable_includes = _torch_includes(needs_python=False)
    common_flags = ["-std=c++17", "-I" + str(TA_DIR)]

    failures = []
    with tempfile.TemporaryDirectory(prefix="ta_header_check_") as tmp:
        tmp = Path(tmp)
        cpp_path = tmp / "ta_check.cpp"
        cu_path = tmp / "ta_check.cu"
        cpp_path.write_text(CPP_TU, encoding="utf-8")
        cu_path.write_text(CU_TU, encoding="utf-8")

        # --- CPU, both build modes ------------------------------------------
        if args.only_cuda:
            print("[skip] aten-cpp   (--only-cuda)")
            print("[skip] stable-cpp (--only-cuda)")
        else:
            for name, defines, includes in (
                ("aten-cpp", [], aten_includes),
                ("stable-cpp", STABLE_DEFINES, stable_includes),
            ):
                reason = cxx_reason or (stable_reason if name.startswith("stable")
                                        else None)
                if reason:
                    print(f"[skip] {name:10} ({reason})")
                    continue
                command = ["g++", "-fsyntax-only"] + common_flags + includes + defines
                command += [cpp_path]
                if not _check(name, command, args.verbose):
                    failures.append(name)

        # --- CUDA, both build modes -----------------------------------------
        if args.no_cuda:
            print("[skip] aten-cu   (--no-cuda)")
            print("[skip] stable-cu (--no-cuda)")
        else:
            reason = _cuda_skip_reason(args.cuda_home, torch_probe)
            if reason:
                print(f"[skip] aten-cu   ({reason})")
                print(f"[skip] stable-cu ({reason})")
            else:
                nvcc, home = _find_nvcc(args.cuda_home)
                ccbin = _find_ccbin(args.ccbin)
                env = dict(os.environ, CUDA_HOME=home)
                cuda_flags = ["-O0", "-gencode", "arch=" + CUDA_ARCH]
                if ccbin:
                    cuda_flags += ["-ccbin", ccbin]
                for name, defines, includes in (
                    ("aten-cu", ATEN_CU_DEFINES, aten_includes),
                    ("stable-cu", STABLE_DEFINES + STABLE_CU_DEFINES,
                     stable_includes),
                ):
                    if name.startswith("stable") and stable_reason:
                        print(f"[skip] {name:10} ({stable_reason})")
                        continue
                    command = [nvcc, "-c"] + common_flags + cuda_flags + includes
                    command += defines + [cu_path, "-o", tmp / (name + ".o")]
                    if args.verbose:
                        print(f"    (CUDA_HOME={home})")
                    result = subprocess.run(
                        [str(part) for part in command], capture_output=True,
                        text=True, env=env)
                    if result.returncode == 0:
                        print(f"[ok]   {name}")
                    else:
                        print(f"[FAIL] {name}")
                        lines = (result.stdout + result.stderr).strip().splitlines()
                        for line in lines[:40]:
                            print("       " + line)
                        if len(lines) > 40:
                            print(f"       ... ({len(lines) - 40} more lines)")
                        failures.append(name)

        if args.keep:
            kept = Path.cwd() / "ta_header_check"
            shutil.copytree(tmp, kept, dirs_exist_ok=True)
            print(f"kept the generated TUs in {kept}")

    if failures:
        print(f"\n{len(failures)} combination(s) failed: {', '.join(failures)}")
        return 1
    print("\nthe ta:: compatibility layer compiles in every combination checked")
    return 0


if __name__ == "__main__":
    sys.exit(main())
